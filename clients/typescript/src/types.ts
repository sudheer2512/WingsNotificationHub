/**
 * Wire contracts of the Wings Notification Hub REST API (mirrors Wings.NotificationHub.Contracts).
 * JSON is camelCase, enums are strings, channels are lower case. Guids are strings; instants are ISO-8601 strings.
 */

export type Guid = string;
/** ISO-8601 timestamp, e.g. "2026-10-28T10:15:00Z". */
export type IsoDateTime = string;
export type JsonValue = string | number | boolean | null | JsonValue[] | { [key: string]: JsonValue };
export type JsonObject = { [key: string]: JsonValue };

export type Channel = 'email' | 'sms' | 'whatsapp' | 'inapp' | 'push' | 'webpush' | 'webhook';
export const CHANNELS: readonly Channel[] = ['email', 'sms', 'whatsapp', 'inapp', 'push', 'webpush', 'webhook'];

export type DeliveryStatus =
  | 'Draft' | 'Scheduled' | 'Queued' | 'Processing' | 'Submitted' | 'ProviderAccepted' | 'Sent' | 'Delivered' | 'Read'
  | 'Failed' | 'RetryPending' | 'Cancelled' | 'Expired' | 'Suppressed' | 'Unknown';

export type RequestStatus =
  | 'Accepted' | 'Scheduled' | 'Processing' | 'Completed' | 'PartiallyFailed' | 'Failed' | 'Cancelled' | 'Suppressed'
  | 'PendingApproval' | 'Rejected';

/** Request statuses after which nothing else will happen to a notification. */
export const FINAL_REQUEST_STATUSES: readonly RequestStatus[] = ['Completed', 'Failed', 'PartiallyFailed', 'Suppressed', 'Cancelled', 'Rejected'];

export type NotificationPriority = 'Low' | 'Normal' | 'High' | 'Critical';
export type MessageClass = 'Transactional' | 'Promotional' | 'Critical';
export type TemplateStatus = 'Draft' | 'InReview' | 'Approved' | 'Active' | 'Retired' | 'Rejected';
export type BodyFormat = 'Text' | 'Html';
export type AttemptOutcome = 'Accepted' | 'PermanentFailure' | 'TransientFailure' | 'Ambiguous' | 'Throttled';
export type ProviderHealthStatus = 'Unknown' | 'Healthy' | 'Degraded' | 'Unhealthy' | 'CircuitOpen';
export type ConsentStatus = 'Granted' | 'Withdrawn';
export type ConsentPurpose = 'ChannelOptIn' | 'Marketing';
export type RequestSource = 'Api' | 'Batch' | 'Event' | 'Schedule' | 'Campaign' | 'Mcp' | 'Admin' | 'Escalation' | 'TestSend';
export type DevicePlatform = 'Android' | 'Ios' | 'Web';
export type ContactKind = 'User' | 'Customer' | 'Other';

